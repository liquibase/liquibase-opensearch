package liquibase.ext.opensearch.change;

import liquibase.change.AbstractChange;
import liquibase.change.ChangeParameterMetaData;
import liquibase.change.DatabaseChange;
import liquibase.change.DatabaseChangeProperty;
import liquibase.database.Database;
import liquibase.exception.ValidationErrors;
import liquibase.ext.opensearch.statement.HttpRequestStatement;
import liquibase.servicelocator.PrioritizedService;
import liquibase.statement.SqlStatement;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.apache.commons.lang3.StringUtils;
import org.apache.hc.core5.http.ContentType;

import java.util.List;
import java.util.Optional;

@DatabaseChange(name = "httpRequest",
        description = "Execute an arbitrary HTTP request with the provided payload",
        priority = PrioritizedService.PRIORITY_DATABASE)
@NoArgsConstructor
@Setter
public class HttpRequestChange extends AbstractChange {

    /**
     * Same as the {@code httpMethods} of the XSD: other methods can't modify data in OpenSearch.
     */
    private static final List<String> ALLOWED_METHODS = List.of("POST", "PUT", "DELETE", "PATCH");

    private String method;
    private String contentType;
    private String path;
    private String body;

    // note: liquibase reads `@DatabaseChangeProperty` from the getters, thus they can't be generated by lombok

    @DatabaseChangeProperty(requiredForDatabase = ChangeParameterMetaData.ALL,
            description = "HTTP method of the request")
    public String getMethod() {
        return this.method;
    }

    @DatabaseChangeProperty(requiredForDatabase = ChangeParameterMetaData.NONE,
            description = "Content type of the body. Defaults to application/json")
    public String getContentType() {
        return this.contentType;
    }

    @DatabaseChangeProperty(requiredForDatabase = ChangeParameterMetaData.ALL,
            description = "Path of the request, e.g. /my-index")
    public String getPath() {
        return this.path;
    }

    @DatabaseChangeProperty(requiredForDatabase = ChangeParameterMetaData.NONE,
            description = "Body of the request. Defaults to an empty body")
    public String getBody() {
        return this.body;
    }

    @Override
    public ValidationErrors validate(final Database database) {
        final var errors = super.validate(database);
        // missing (null or blank) values have already been reported by `super.validate`
        if (StringUtils.isNotBlank(this.method) && !ALLOWED_METHODS.contains(this.method)) {
            errors.addError("method must be one of %s but was '%s'".formatted(String.join(", ", ALLOWED_METHODS), this.method));
        }
        if (StringUtils.isNotBlank(this.path) && !this.path.startsWith("/")) {
            errors.addError("path must start with '/' but was '%s'".formatted(this.path));
        }
        return errors;
    }

    @Override
    public String getConfirmationMessage() {
        return String.format("executed the HTTP %s request against %s (with a body of size %d and content type %s)",
                this.getMethod(),
                this.getPath(),
                Optional.ofNullable(this.getBody()).map(String::length).orElse(0),
                Optional.ofNullable(this.getContentType()).orElse(ContentType.APPLICATION_JSON.getMimeType()));
    }

    @Override
    public SqlStatement[] generateStatements(final Database database) {
        return new SqlStatement[] {
            new HttpRequestStatement(this.getMethod(), this.getContentType(), this.getPath(), this.getBody())
        };
    }
}
